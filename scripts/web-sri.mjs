// Subresource Integrity for the portal pages.
//
//   node scripts/web-sri.mjs --write   rewrite the integrity block in every page
//   node scripts/web-sri.mjs --check   fail when a page's block is out of date
//
// Each web/*/index.html carries a block between "sri:begin" and "sri:end"
// comments: the entry <script type="module"> plus one <link rel="modulepreload">
// for every module it imports, directly or not. All of them carry an
// integrity="sha384-..." hash of the file served next to the page. SRI on the
// entry script alone would not cover its imports; a modulepreload with an
// integrity hash is what makes the browser check an imported module against
// that hash. The CSP stays strict (script-src 'self', no inline scripts, no
// import map, which would have to be inline).
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, normalize, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "web");
const BEGIN = "<!-- sri:begin (generated by scripts/web-sri.mjs; do not edit) -->";
const END = "<!-- sri:end -->";

const integrity = (file) => "sha384-" + createHash("sha384").update(readFileSync(file)).digest("base64");

// Static imports only: the pages use no dynamic import().
function imports(file) {
  const src = readFileSync(file, "utf8");
  const out = [];
  for (const m of src.matchAll(/(?:^|\n)\s*(?:import|export)\b[^"';]*?\bfrom\s*["']([^"']+)["']|(?:^|\n)\s*import\s*["']([^"']+)["']/g)) {
    const spec = m[1] ?? m[2];
    if (!spec.startsWith("./") && !spec.startsWith("../")) throw new Error(`${file}: non-relative import ${spec}`);
    out.push(normalize(join(dirname(file), spec)));
  }
  if (/\bimport\s*\(/.test(src)) throw new Error(`${file}: dynamic import() is not covered by SRI`);
  return out;
}

function closure(entry) {
  const seen = new Set();
  const walk = (f) => {
    if (seen.has(f)) return;
    seen.add(f);
    imports(f).forEach(walk);
  };
  walk(entry);
  seen.delete(entry);
  return [...seen].sort();
}

function block(page) {
  const dir = dirname(page);
  const html = readFileSync(page, "utf8");
  const m = html.match(/<script type="module" src="([^"]+)"[^>]*><\/script>/);
  if (!m) throw new Error(`${page}: no module script`);
  const entry = normalize(join(dir, m[1]));
  const href = (f) => m[1].replace(/[^/]+$/, "") + f.slice(dirname(entry).length + 1);
  const lines = [BEGIN];
  lines.push(`<script type="module" src="${m[1]}" integrity="${integrity(entry)}"></script>`);
  for (const dep of closure(entry)) {
    lines.push(`<link rel="modulepreload" href="${href(dep)}" integrity="${integrity(dep)}">`);
  }
  lines.push(END);
  return { html, text: lines.map((l, i) => (i ? "  " : "") + l).join("\n"), script: m[0] };
}

function rewrite(page) {
  const { html, text, script } = block(page);
  const had = html.includes(BEGIN);
  if (had) {
    const a = html.indexOf(BEGIN);
    const b = html.indexOf(END) + END.length;
    return html.slice(0, a) + text + html.slice(b);
  }
  return html.replace(script, text);
}

// block() reads an existing page; on a page that already has a block the
// entry script is inside it, which the regex above still matches.
const pages = readdirSync(root, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => join(root, d.name, "index.html"))
  .filter((p) => { try { readFileSync(p); return true; } catch { return false; } });

const mode = process.argv[2];
if (mode !== "--write" && mode !== "--check") {
  console.error("usage: web-sri.mjs --write | --check");
  process.exit(2);
}
let stale = 0;
for (const p of pages) {
  const want = rewrite(p);
  if (want === readFileSync(p, "utf8")) continue;
  if (mode === "--write") writeFileSync(p, want);
  else { console.error(`${p}: integrity block out of date; run: make web-sri`); stale++; }
}
process.exit(stale ? 1 : 0);
