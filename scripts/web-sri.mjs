// Pins every portal script with subresource integrity.
//
//   node scripts/web-sri.mjs --write [webdir]   rewrite the sri block of web/*/index.html
//   node scripts/web-sri.mjs --check [webdir]   fail when a block is out of date, or when
//                                               any script or modulepreload in a page
//                                               lacks integrity, has a stale hash, or
//                                               names a file web/embed.go does not embed
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, normalize, posix, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const BEGIN = "<!-- sri:begin (generated by scripts/web-sri.mjs; do not edit) -->";
const END = "<!-- sri:end -->";

const integrity = (file) => "sha384-" + createHash("sha384").update(readFileSync(file)).digest("base64");

// The files the engine embeds and the portal publishes: the patterns of the
// //go:embed line in web/embed.go, expanded (a literal path or dir/*.ext).
export function embedded(root) {
  const src = readFileSync(join(root, "embed.go"), "utf8");
  const lines = [...src.matchAll(/^\/\/go:embed (.+)$/gm)];
  if (lines.length !== 1) throw new Error(`${root}/embed.go: want exactly one //go:embed line, found ${lines.length}`);
  const m = lines[0];
  const out = new Set();
  for (const pat of m[1].trim().split(/\s+/)) {
    if (/[?[\\"`]/.test(pat)) throw new Error(`unsupported embed pattern ${pat}`);
    const star = pat.indexOf("*");
    if (star < 0) { out.add(pat); continue; }
    const dir = posix.dirname(pat);
    const base = posix.basename(pat);
    if (dir.includes("*") || base.indexOf("*") !== base.lastIndexOf("*")) throw new Error(`unsupported embed pattern ${pat}`);
    const [pre, post] = base.split("*");
    for (const f of readdirSync(join(root, dir))) {
      if (f.startsWith(pre) && f.endsWith(post) && f.length >= pre.length + post.length) out.add(`${dir}/${f}`);
    }
  }
  return out;
}

// resolveRef maps a reference in a file under root to its embedded path, or
// throws when it is not relative, leaves root, or names a file not embedded.
function resolveRef(root, files, from, ref) {
  if (/^[a-z][a-z0-9+.-]*:|^\/\//i.test(ref) || ref.startsWith("/")) throw new Error(`${from}: reference ${ref} is not relative to the page`);
  const clean = posix.normalize(ref);
  if (clean !== ref && "./" + clean !== ref) throw new Error(`${from}: reference ${ref} is not in clean form`);
  const rel = posix.normalize(posix.join(posix.dirname(relative(root, from).split(sep).join("/")), ref));
  if (rel.startsWith("../") || rel === "..") throw new Error(`${from}: reference ${ref} leaves the embedded files`);
  if (!files.has(rel)) throw new Error(`${from}: reference ${ref} is not an embedded file`);
  return join(root, rel);
}

// IMPORT_FROM reads a static import (or export ... from) that starts a line.
// Its clause holds no quote, semicolon, parenthesis or slash, so it cannot
// swallow an import() call, a second statement or a comment.
const IMPORT_FROM = /(?:^|\n)[ \t]*(?:import|export)\b[^"';()`/]*?\bfrom[ \t]*["']([^"']+)["']|(?:^|\n)[ \t]*import[ \t]*["']([^"']+)["']/g;
// import( with white space or // comments between (block comments are
// refused outright, see imports).
const DYNAMIC_IMPORT = /\bimport(?:\s|\/\/[^\n]*\n)*\(/;
// An import or export-from IMPORT_FROM did not read: one not at the start of
// a line, import.meta, or the word in a string or comment. Comments are not
// skipped: a line that starts with // can still end a template literal or a
// continued string and go on as code.
const STRAY_IMPORT = /\bimport\b|\bfrom\s*["'`]/;
// A way to run code or load a document that no modulepreload integrity
// covers: script elements (any "script" string, createElementNS for the SVG
// one), workers, worklets, frames, objects and embeds. It
// catches a mistake, not deliberate obfuscation ("scr" + "ipt"). The pages'
// meta CSP (default-src 'none') blocks frames and objects as well, but not
// script elements or workers: script-src 'self' admits any same-origin
// script without integrity.
const UNPINNED_LOAD = new RegExp(
  "\\b(?:worker|sharedworker|serviceworker|importscripts|[a-z]*worklet|addmodule|iframe|frameset|srcdoc|htmliframeelement|htmlobjectelement|htmlembedelement|htmlscriptelement|svgscriptelement|createelementns)\\b" +
  "|[\"'`]script[\"'`]|<\\s*(?:script|frame|object|embed|portal|applet)\\b|\\(\\s*[\"'`](?:frame|object|embed|portal|applet)[\"'`]", "i");

// imports returns the embedded files a module imports, and throws on any way
// it could load code that no modulepreload integrity covers, or on an import
// it cannot read.
export function imports(root, files, file) {
  const src = readFileSync(file, "utf8");
  // JavaScript ends a line (and a // comment) at each of these.
  if (/[\r\u2028\u2029]/.test(src)) throw new Error(`${file}: line terminator other than LF`);
  // A block comment can make the line-based reading below see code as
  // commented out, or the other way round, so modules use // only.
  if (src.includes("/*")) throw new Error(`${file}: block comment (use // comments)`);
  if (DYNAMIC_IMPORT.test(src)) throw new Error(`${file}: dynamic import() is not covered by SRI`);
  const load = src.match(UNPINNED_LOAD);
  if (load) throw new Error(`${file}: ${load[0]} loads code or a document that SRI does not cover`);
  const code = src;
  const stray = code.replace(IMPORT_FROM, " ").match(STRAY_IMPORT);
  if (stray) throw new Error(`${file}: an import the scanner cannot account for (${stray[0]}); write each import at the start of a line`);
  const out = [];
  for (const m of code.matchAll(IMPORT_FROM)) {
    const spec = m[1] ?? m[2];
    if (!spec.startsWith("./") && !spec.startsWith("../")) throw new Error(`${file}: non-relative import ${spec}`);
    out.push(resolveRef(root, files, file, spec));
  }
  return out;
}

function closure(root, files, entry) {
  const seen = new Set();
  const walk = (f) => {
    if (seen.has(f)) return;
    seen.add(f);
    imports(root, files, f).forEach(walk);
  };
  walk(entry);
  seen.delete(entry);
  return [...seen].sort();
}

function block(root, files, page) {
  const html = plainUTF8(page);
  const m = html.match(/<script type="module" src="([^"]+)"[^>]*><\/script>/);
  if (!m) throw new Error(`${page}: no module script`);
  const entry = resolveRef(root, files, page, m[1]);
  const href = (f) => m[1].replace(/[^/]+$/, "") + f.slice(dirname(entry).length + 1);
  const lines = [BEGIN];
  for (const dep of closure(root, files, entry)) {
    lines.push(`<link rel="modulepreload" href="${href(dep)}" integrity="${integrity(dep)}">`);
  }
  lines.push(`<script type="module" src="${m[1]}" integrity="${integrity(entry)}"></script>`);
  lines.push(END);
  return { html, text: lines.map((l, i) => (i ? "  " : "") + l).join("\n"), script: m[0] };
}

function rewrite(root, files, page) {
  const { html, text, script } = block(root, files, page);
  if (html.includes(BEGIN)) {
    const a = html.indexOf(BEGIN);
    const b = html.indexOf(END) + END.length;
    return html.slice(0, a) + text + html.slice(b);
  }
  return html.replace(script, text);
}

// verify checks every script and link tag of a page, wherever it sits
// (inside the generated block or not). Each must have one of the exact forms
// the generator writes (or a plain stylesheet link): any other shape fails,
// so a decoy attribute (data-src=, a src="..." inside another value) cannot
// point the check at one file while the browser loads another. Scripts and
// modulepreloads must name an embedded file and carry its hash, and the
// preloads must come before the first script. Returns the problems found.
const SCRIPT = /^<script type="module" src="([^"&]+)" integrity="(sha384-[A-Za-z0-9+/]+=*)"><\/script>/;
const PRELOAD = /^<link rel="modulepreload" href="([^"&]+)" integrity="(sha384-[A-Za-z0-9+/]+=*)">/;
const STYLE = /^<link rel="stylesheet" href="([^"&]+)">/;

// plainUTF8 refuses a page the browser might decode differently from the
// check: a byte-order mark (it overrides the declared charset, so a UTF-16
// page would hide its tags from this scan), invalid UTF-8, control bytes
// other than tab, LF and CR (ESC switches ISO-2022 encodings), or any charset
// other than one <meta charset="utf-8"> in the first 1024 bytes.
export function plainUTF8(page) {
  const bytes = readFileSync(page);
  let html;
  try {
    html = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true }).decode(bytes);
  } catch {
    throw new Error(`${page}: not valid UTF-8`);
  }
  if (html.startsWith("\uFEFF")) throw new Error(`${page}: starts with a byte-order mark`);
  const ctrl = html.match(/[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]/);
  if (ctrl) throw new Error(`${page}: control byte 0x${ctrl[0].charCodeAt(0).toString(16).padStart(2, "0")}`);
  const meta = '<meta charset="utf-8">';
  const at = bytes.indexOf(meta);
  if (at < 0 || at + meta.length > 1024 || (html.match(/charset/gi) || []).length !== 1) {
    throw new Error(`${page}: must declare exactly one charset, ${meta}, in its first 1024 bytes`);
  }
  return html;
}

// The only lines a page head may hold besides the sri block. Each is a whole,
// self-contained tag: none can open a context (template, noscript, an
// attribute value, title text) that would make the block inert to the
// browser while this check still reads it.
const HEAD_LINE = new RegExp("^(?:" + [
  '<meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width, initial-scale=1">',
  '<meta name="referrer" content="no-referrer">',
  '<meta name="robots" content="noindex">',
  '<title>[^<>&"]*</title>',
  '<link rel="stylesheet" href="[^"&]+">',
].join("|") + ")$");
// The meta CSP every page carries, before its sri block: it falls back to
// default-src 'none', so frames and objects stay blocked even where a host
// serves the page under a looser header (the portal's _headers falls back to
// 'self'). It does not block workers or script elements (script-src 'self').
// Only connect-src may differ.
const CSP_LINE = /^<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'self'; style-src 'self'; img-src 'self'; font-src 'self'; connect-src '(?:self|none)'; base-uri 'none'; form-action 'none'">$/;
const CSP_PREFIX = '<meta http-equiv="Content-Security-Policy"';
// A tag the body may not hold: one that loads a script, sets page metadata,
// or frames or embeds another document (an <iframe srcdoc> would run markup
// that no integrity check reads).
const BODY_TAG = /<(script|link|meta|base|head|iframe|frame|frameset|object|embed|portal|applet)\b/i;
const PRELOAD_LINE = new RegExp(PRELOAD.source + "$");
const SCRIPT_LINE = new RegExp(SCRIPT.source + "$");
const PROLOGUE = '<!doctype html>\n<html lang="en">\n<head>\n';

// pageHead checks the fixed prologue and that no BODY_TAG follows </head>,
// and returns the head.
function pageHead(page, html) {
  if (!html.startsWith(PROLOGUE)) throw new Error(`${page}: does not start with the fixed prologue`);
  const end = html.indexOf("\n</head>\n", PROLOGUE.length);
  if (end < 0) throw new Error(`${page}: no </head> line`);
  const tag = html.slice(end + "\n</head>\n".length).match(BODY_TAG);
  if (tag) throw new Error(`${page}: ${tag[0]} after the head`);
  return html.slice(PROLOGUE.length, end);
}

// pageShape pins where the sri block sits: the fixed prologue, a head of
// allow-listed lines with exactly one meta CSP line (CSP_LINE) and exactly
// one sri block (the preloads, then one module script), and no BODY_TAG
// after </head>.
function pageShape(page, html) {
  let state = "before";
  let csp = 0;
  for (let line of pageHead(page, html).split("\n")) {
    line = line.replace(/^ +/, "");
    if (state === "before" && CSP_LINE.test(line)) csp++;
    else if (line.startsWith(CSP_PREFIX)) throw new Error(`${page}: the meta CSP line must be the fixed one, with default-src 'none', before the sri block: ${line}`);
    else if (state === "before" && line === BEGIN) state = "preloads";
    else if (state === "preloads" && PRELOAD_LINE.test(line)) continue;
    else if (state === "preloads" && SCRIPT_LINE.test(line)) state = "script";
    else if (state === "script" && line === END) state = "after";
    else if ((state === "before" || state === "after") && HEAD_LINE.test(line)) continue;
    else throw new Error(`${page}: head line is not in a checked form (run make web-sri): ${line}`);
  }
  if (state !== "after") throw new Error(`${page}: no complete sri block in the head`);
  if (csp !== 1) throw new Error(`${page}: needs exactly one meta CSP line with default-src 'none', before the sri block (found ${csp})`);
}

export function verify(root, files, page) {
  const problems = [];
  let html;
  try {
    html = plainUTF8(page);
  } catch (e) {
    return [e.message];
  }
  const entries = [];
  const declared = new Set();
  const pinned = (ref, hash) => {
    const file = resolveRef(root, files, page, ref);
    if (integrity(file) !== hash) throw new Error(`${page}: stale integrity for ${ref}`);
    return file;
  };
  let scripts = 0;
  for (const t of html.matchAll(/<(script|link)\b/gi)) {
    const rest = html.slice(t.index);
    try {
      let m;
      if ((m = rest.match(SCRIPT))) { entries.push(pinned(m[1], m[2])); scripts++; }
      else if ((m = rest.match(PRELOAD))) {
        if (scripts) throw new Error(`${page}: modulepreload after the module script`);
        declared.add(pinned(m[1], m[2]));
      } else if ((m = rest.match(STYLE))) resolveRef(root, files, page, m[1]);
      else throw new Error(`${page}: tag is not in a checked form (run make web-sri): ${rest.split(">")[0]}>`);
    } catch (e) {
      problems.push(e.message);
    }
  }
  if (!scripts) problems.push(`${page}: no script`);
  // Every module any entry script imports, directly or not, needs a preload
  // with integrity: the generated block covers the first script only.
  for (const entry of entries) {
    try {
      for (const dep of closure(root, files, entry)) {
        if (!declared.has(dep)) problems.push(`${page}: imported module ${relative(root, dep)} has no modulepreload with integrity`);
      }
    } catch (e) {
      problems.push(e.message);
    }
  }
  try {
    pageShape(page, html);
  } catch (e) {
    problems.push(e.message);
  }
  return [...new Set(problems)];
}

// The portal's root pages, index.html and 404.html, load no script, so they
// have no sri block. Cloudflare Pages serves 404.html at any unknown path,
// whatever its depth, so they name the stylesheet by its absolute path. The
// engine embeds them for basalt portal verify but never serves them.
// STATIC_CSP_LINE allows no script at all; STATIC_STYLE_LINE is the only
// link they may hold.
const STATIC_CSP_LINE = `<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'self'; font-src 'self'; base-uri 'none'; form-action 'none'">`;
const STATIC_STYLE_LINE = '<link rel="stylesheet" href="/style.css">';

// verifyStatic checks a root page: the fixed prologue, a head of allow-listed
// lines with exactly the static meta CSP line and the one stylesheet link,
// no script or other link anywhere, and no BODY_TAG after </head>.
export function verifyStatic(root, files, page) {
  let html;
  try {
    html = plainUTF8(page);
  } catch (e) {
    return [e.message];
  }
  if (!files.has("style.css")) return [`${page}: style.css is not embedded`];
  let head;
  try {
    head = pageHead(page, html);
  } catch (e) {
    return [e.message];
  }
  const problems = [];
  let csp = 0;
  let style = 0;
  for (let line of head.split("\n")) {
    line = line.replace(/^ +/, "");
    if (line === STATIC_CSP_LINE) csp++;
    else if (line === STATIC_STYLE_LINE) style++;
    else if (line.startsWith(CSP_PREFIX)) problems.push(`${page}: the meta CSP line must be the fixed one for a page without script: ${line}`);
    else if (/^<link\b/i.test(line) || !HEAD_LINE.test(line)) problems.push(`${page}: head line is not in a checked form: ${line}`);
  }
  if (csp !== 1) problems.push(`${page}: needs exactly one meta CSP line, the one for a page without script (found ${csp})`);
  if (style !== 1) problems.push(`${page}: needs exactly one stylesheet link, ${STATIC_STYLE_LINE} (found ${style})`);
  return problems;
}

export function run(mode, root) {
  const files = embedded(root);
  const pages = [...files].filter((f) => /^[^/]+\/index\.html$/.test(f)).sort().map((f) => join(root, f));
  let bad = 0;
  for (const f of [...files].filter((f) => /^[^/]+\.html$/.test(f)).sort()) {
    for (const problem of verifyStatic(root, files, join(root, f))) { console.error(problem); bad++; }
  }
  for (const p of pages) {
    let want;
    try {
      want = rewrite(root, files, p);
    } catch (e) {
      console.error(e.message);
      bad++;
      continue;
    }
    if (want !== readFileSync(p, "utf8")) {
      if (mode === "--write") writeFileSync(p, want);
      else { console.error(`${p}: integrity block out of date; run: make web-sri`); bad++; }
    }
    for (const problem of verify(root, files, p)) { console.error(problem); bad++; }
  }
  return bad ? 1 : 0;
}

if (process.argv[1] && normalize(resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  if (mode !== "--write" && mode !== "--check") {
    console.error("usage: web-sri.mjs --write | --check [webdir]");
    process.exit(2);
  }
  const root = resolve(process.argv[3] ?? join(dirname(fileURLToPath(import.meta.url)), "..", "web"));
  process.exit(run(mode, root));
}
