package guard

import (
	"fmt"

	"github.com/basaltdbhq/basaltdb/internal/core/guardmodel"
	"github.com/basaltdbhq/basaltdb/internal/core/setupcode"
)

// RepairScript is the Update check's REPAIR for agent (CONTRACT.md, Setup
// page, The Update check): the plain-agent-role checks and the settings
// reset basalt init runs on a role that exists, then password as the role's
// new password, sent as its SCRAM-SHA-256 verifier and shown redacted. The
// role must be an agent of n's group already. It changes no grant, policy,
// label or passkey. The caller runs it in one transaction.
func RepairScript(n guardmodel.Names, agent, password string, timeoutMs int64) (guardmodel.Script, error) {
	role, err := n.Agent(agent)
	if err != nil {
		return guardmodel.Script{}, err
	}
	if password == "" || !isHex(password) {
		return guardmodel.Script{}, fmt.Errorf("%w: password must be generated by NewPassword", guardmodel.ErrInvalidAgent)
	}
	adopt, err := agentAdoptStatement(n, role, guardmodel.AgentSpec{})
	if err != nil {
		return guardmodel.Script{}, err
	}
	verifier, err := setupcode.NewVerifier(password)
	if err != nil {
		return guardmodel.Script{}, fmt.Errorf("%w: %w", guardmodel.ErrInvalidAgent, err)
	}
	render := func(v string) string {
		return renderSQL(n, fmt.Sprintf(agentAlterRoleSQL, role, quoteLiteral(v), timeoutMs, setupcode.AgentConnectionLimit))
	}
	return guardmodel.Script{Statements: []guardmodel.Statement{adopt, {SQL: render(verifier), Shown: render(redacted)}}}, nil
}
