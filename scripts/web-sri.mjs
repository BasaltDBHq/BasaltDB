// Pins every portal script with subresource integrity.
//
//   node scripts/web-sri.mjs --write [webdir]   rewrite the sri block of web/*/index.html
//   node scripts/web-sri.mjs --check [webdir]   fail when a block is out of date, or when
//                                               any script or modulepreload in a page
//                                               lacks integrity, has a stale hash, or
//                                               names a file web/embed.go does not embed
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, normalize, posix, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const BEGIN = "<!-- sri:begin (generated by scripts/web-sri.mjs; do not edit) -->";
const END = "<!-- sri:end -->";

const integrity = (file) => "sha384-" + createHash("sha384").update(readFileSync(file)).digest("base64");

// The files the engine embeds and the portal publishes: the patterns of the
// //go:embed line in web/embed.go, expanded (a literal path or dir/*.ext).
export function embedded(root) {
  const src = readFileSync(join(root, "embed.go"), "utf8");
  const m = src.match(/^\/\/go:embed (.+)$/m);
  if (!m) throw new Error(`${root}/embed.go: no //go:embed line`);
  const out = new Set();
  for (const pat of m[1].trim().split(/\s+/)) {
    const star = pat.indexOf("*");
    if (star < 0) { out.add(pat); continue; }
    const dir = posix.dirname(pat);
    const base = posix.basename(pat);
    if (dir.includes("*") || base.indexOf("*") !== base.lastIndexOf("*")) throw new Error(`unsupported embed pattern ${pat}`);
    const [pre, post] = base.split("*");
    for (const f of readdirSync(join(root, dir))) {
      if (f.startsWith(pre) && f.endsWith(post) && f.length >= pre.length + post.length) out.add(`${dir}/${f}`);
    }
  }
  return out;
}

// resolveRef maps a reference in a file under root to its embedded path, or
// throws when it is not relative, leaves root, or names a file not embedded.
function resolveRef(root, files, from, ref) {
  if (/^[a-z][a-z0-9+.-]*:|^\/\//i.test(ref) || ref.startsWith("/")) throw new Error(`${from}: reference ${ref} is not relative to the page`);
  const rel = posix.normalize(posix.join(posix.dirname(relative(root, from).split(sep).join("/")), ref));
  if (rel.startsWith("../") || rel === "..") throw new Error(`${from}: reference ${ref} leaves the embedded files`);
  if (!files.has(rel)) throw new Error(`${from}: reference ${ref} is not an embedded file`);
  return join(root, rel);
}

function imports(root, files, file) {
  const src = readFileSync(file, "utf8");
  const out = [];
  for (const m of src.matchAll(/(?:^|\n)\s*(?:import|export)\b[^"';]*?\bfrom\s*["']([^"']+)["']|(?:^|\n)\s*import\s*["']([^"']+)["']/g)) {
    const spec = m[1] ?? m[2];
    if (!spec.startsWith("./") && !spec.startsWith("../")) throw new Error(`${file}: non-relative import ${spec}`);
    out.push(resolveRef(root, files, file, spec));
  }
  if (/\bimport\s*\(/.test(src)) throw new Error(`${file}: dynamic import() is not covered by SRI`);
  return out;
}

function closure(root, files, entry) {
  const seen = new Set();
  const walk = (f) => {
    if (seen.has(f)) return;
    seen.add(f);
    imports(root, files, f).forEach(walk);
  };
  walk(entry);
  seen.delete(entry);
  return [...seen].sort();
}

function block(root, files, page) {
  const html = readFileSync(page, "utf8");
  const m = html.match(/<script type="module" src="([^"]+)"[^>]*><\/script>/);
  if (!m) throw new Error(`${page}: no module script`);
  const entry = resolveRef(root, files, page, m[1]);
  const href = (f) => m[1].replace(/[^/]+$/, "") + f.slice(dirname(entry).length + 1);
  const lines = [BEGIN];
  for (const dep of closure(root, files, entry)) {
    lines.push(`<link rel="modulepreload" href="${href(dep)}" integrity="${integrity(dep)}">`);
  }
  lines.push(`<script type="module" src="${m[1]}" integrity="${integrity(entry)}"></script>`);
  lines.push(END);
  return { html, text: lines.map((l, i) => (i ? "  " : "") + l).join("\n"), script: m[0] };
}

function rewrite(root, files, page) {
  const { html, text, script } = block(root, files, page);
  if (html.includes(BEGIN)) {
    const a = html.indexOf(BEGIN);
    const b = html.indexOf(END) + END.length;
    return html.slice(0, a) + text + html.slice(b);
  }
  return html.replace(script, text);
}

// verify checks every script and link tag of a page, wherever it sits
// (inside the generated block or not). Each must have one of the exact forms
// the generator writes (or a plain stylesheet link): any other shape fails,
// so a decoy attribute (data-src=, a src="..." inside another value) cannot
// point the check at one file while the browser loads another. Scripts and
// modulepreloads must name an embedded file and carry its hash, and the
// preloads must come before the first script. Returns the problems found.
const SCRIPT = /^<script type="module" src="([^"&]+)" integrity="(sha384-[A-Za-z0-9+/]+=*)"><\/script>/;
const PRELOAD = /^<link rel="modulepreload" href="([^"&]+)" integrity="(sha384-[A-Za-z0-9+/]+=*)">/;
const STYLE = /^<link rel="stylesheet" href="([^"&]+)">/;

export function verify(root, files, page) {
  const html = readFileSync(page, "utf8");
  const problems = [];
  const pinned = (ref, hash) => {
    const file = resolveRef(root, files, page, ref);
    if (integrity(file) !== hash) throw new Error(`${page}: stale integrity for ${ref}`);
  };
  let scripts = 0;
  for (const t of html.matchAll(/<(script|link)\b/gi)) {
    const rest = html.slice(t.index);
    try {
      let m;
      if ((m = rest.match(SCRIPT))) { pinned(m[1], m[2]); scripts++; }
      else if ((m = rest.match(PRELOAD))) {
        if (scripts) throw new Error(`${page}: modulepreload after the module script`);
        pinned(m[1], m[2]);
      } else if ((m = rest.match(STYLE))) resolveRef(root, files, page, m[1]);
      else throw new Error(`${page}: tag is not in a checked form (run make web-sri): ${rest.split(">")[0]}>`);
    } catch (e) {
      problems.push(e.message);
    }
  }
  if (!scripts) problems.push(`${page}: no script`);
  return problems;
}

export function run(mode, root) {
  const files = embedded(root);
  const pages = [...files].filter((f) => /^[^/]+\/index\.html$/.test(f)).sort().map((f) => join(root, f));
  let bad = 0;
  for (const p of pages) {
    let want;
    try {
      want = rewrite(root, files, p);
    } catch (e) {
      console.error(e.message);
      bad++;
      continue;
    }
    if (want !== readFileSync(p, "utf8")) {
      if (mode === "--write") writeFileSync(p, want);
      else { console.error(`${p}: integrity block out of date; run: make web-sri`); bad++; continue; }
    }
    for (const problem of verify(root, files, p)) { console.error(problem); bad++; }
  }
  return bad ? 1 : 0;
}

if (process.argv[1] && normalize(resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  if (mode !== "--write" && mode !== "--check") {
    console.error("usage: web-sri.mjs --write | --check [webdir]");
    process.exit(2);
  }
  const root = resolve(process.argv[3] ?? join(dirname(fileURLToPath(import.meta.url)), "..", "web"));
  process.exit(run(mode, root));
}
